/**
 * The Lucide icon a Lucide scope draws for Material symbol `name`, or
 * undefined when it keeps its Material drawing (marked {@link MATERIAL_ONLY},
 * or — until `icons:lucide-coverage` is fixed — not in the map at all).
 */
export function lucideNameOf(name: string): LucideName | undefined {
  const entry = (LUCIDE_MAP as Readonly<Record<string, LucideEntry>>)[name];
  return entry === undefined || entry === MATERIAL_ONLY ? undefined : entry;
}
